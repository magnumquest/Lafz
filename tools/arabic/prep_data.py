"""Prepare training / evaluation files from the Arabic data bundle (see DATA below) into ./work/ (git-ignored).

    DATA=/path/to/Arabic python3 prep_data.py

work/train_pairs.tsv   arabic, roman, count, group weight, group   -> train_channel.py
work/dev_real.tsv      roman, arabic     held-out real chat words (never used for training, spellings, or variants)
work/real_train.tsv    arabic, roman, count   real chat spellings of the training words (observed variants of the eval model)
work/real_all.tsv      same for all real words (observed variants of the shipping model)
Groups: real chat Arabizi (each word weight 1), hand-written religious terms (1), generated typed-style spellings of Qur'an/Hadith words
(0.3 per word: generated by rules from vowelled text, so they must not fully outvote real writing, but scripture words are the main use)."""
import csv, os, re, random, collections, sys

DATA = os.environ.get('DATA', 'data/Arabic')
os.makedirs('work', exist_ok=True)
AR = re.compile('^[ءآأؤإئابةتثجحخدذرزسشصضطظعغفقكلمنهوىي]+$')
SIMPLE = re.compile(r"^[a-z0-9']+$")
random.seed(7)

real = collections.defaultdict(collections.Counter)
for r in csv.DictReader(open(f'{DATA}/pairs/arabizi_pairs.tsv', encoding='utf-8'), delimiter='\t'):
    a, ro = r['arabic'].strip(), r['roman'].strip().lower()
    if AR.match(a) and SIMPLE.match(ro) and int(r['n_words']) == 1:
        real[a][ro] += 1
words = sorted(real)
random.shuffle(words)
dev = set(words[:int(len(words) * 0.08)])
with open('work/dev_real.tsv', 'w', encoding='utf-8') as f, open('work/real_train.tsv', 'w', encoding='utf-8') as g, \
        open('work/real_all.tsv', 'w', encoding='utf-8') as h:
    for a in words:
        for ro, n in real[a].items():
            h.write(f'{a}\t{ro}\t{n}\n')
            if a in dev: f.write(f'{ro}\t{a}\n')
            else: g.write(f'{a}\t{ro}\t{n}\n')
n = collections.Counter()
with open('work/train_pairs.tsv', 'w', encoding='utf-8') as out:
    for a in words:
        if a in dev: continue
        for ro, c in real[a].items(): out.write(f'{a}\t{ro}\t{c}\t1.0\treal\n'); n['real'] += 1
    terms = [l.rstrip('\n').split('\t') for l in open(f'{DATA}/pairs/religious_terms_curated.tsv', encoding='utf-8')]
    terms = [t for t in terms if len(t) >= 2 and t[0] != 'arabic' and ' ' not in t[0] and AR.match(t[0])]
    with open('work/dev_religious.tsv', 'w', encoding='utf-8') as dr:
        for i, p in enumerate(terms):
            for ro in p[1].split(','):
                ro = ro.strip().lower().replace(' ', '')
                if not SIMPLE.match(ro): continue
                if i % 5 == 0: dr.write(f'{ro}\t{p[0]}\n'); n['dev_religious'] += 1     # every 5th hand-written term is held out
                else: out.write(f'{p[0]}\t{ro}\t1\t1.0\tcurated\n'); n['curated'] += 1
    for r in csv.DictReader(open(f'{DATA}/pairs/pairs_synthetic.tsv', encoding='utf-8'), delimiter='\t'):
        a, ro = r['arabic'], r['roman']
        if AR.match(a) and SIMPLE.match(ro) and float(r['weight']) >= 0.01:
            out.write(f'{a}\t{ro}\t{r["weight"]}\t0.3\tsynthetic\n'); n['synthetic'] += 1
print('real words', len(words), 'dev words', len(dev), 'train rows', dict(n))
